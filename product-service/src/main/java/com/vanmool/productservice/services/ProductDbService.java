package com.vanmool.productservice.services;

import com.vanmool.productservice.dtos.ProductResponseDto;
import com.vanmool.productservice.exceptions.ProductNotFoundException;
import com.vanmool.productservice.models.Category;
import com.vanmool.productservice.models.Product;
import com.vanmool.productservice.repositories.CategoryRepository;
import com.vanmool.productservice.repositories.ProductRepository;
import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.github.fge.jsonpatch.JsonPatch;
import com.github.fge.jsonpatch.JsonPatchException;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Optional;

@Service
public class ProductDbService implements ProductService{
    private final CategoryRepository categoryRepository;
    private final ProductRepository productRepository;

    public ProductDbService(CategoryRepository categoryRepository, ProductRepository productRepository) {
        this.categoryRepository = categoryRepository;
        this.productRepository = productRepository;
    }

    @Override
    public Product getProductById(long id) throws ProductNotFoundException {
        Optional<Product> productOptional = productRepository.findByIdAndDeletedFalse(id);
        if(productOptional.isEmpty()) {
            throw new ProductNotFoundException("Product with id " + id + " not found");
        }

        return productOptional.get() ;
    }

    @Override
    public List<Product> getAllProducts() {
        return productRepository.findAllByDeletedFalse();
    }

    @Override
    public Product createProduct(String name, String description, double price,  String imageUrl, String category) {
        Product product = new Product();
        buildProduct(product,name, description, price, imageUrl, category);

        return productRepository.save(product);
    }

    @Override
    public Product replaceProduct(long id, String name, String description, double price, String imageUrl, String category) throws ProductNotFoundException {
        // Ids are generated by the database, so PUT can only replace an existing product; creating is done by POST
        Product product = getProductById(id);
        buildProduct(product,name, description, price, imageUrl, category);

        return productRepository.save(product);
    }

    @Override
    public Product patchProduct(long id, JsonPatch patch) throws ProductNotFoundException, JsonPatchException, JsonProcessingException {
        Product existingProduct = getProductById(id);

        // Apply the patch to the same JSON that GET returns (the DTO), not to the entity
        ObjectMapper objectMapper = new ObjectMapper();
        JsonNode productNode = objectMapper.valueToTree(ProductResponseDto.from(existingProduct));
        JsonNode patchedNode = patch.apply(productNode);
        ProductResponseDto patchedProduct = objectMapper.treeToValue(patchedNode, ProductResponseDto.class);

        buildProduct(existingProduct,
                patchedProduct.getName(),
                patchedProduct.getDescription(),
                patchedProduct.getPrice(),
                patchedProduct.getImageUrl(),
                patchedProduct.getCategory());

        return productRepository.save(existingProduct);
    }

    @Override
    public void deleteProduct(long id) throws ProductNotFoundException {
        // Soft delete: the row stays, so anything that refers to this product id keeps working
        Product product = getProductById(id);
        product.setDeleted(true);
        productRepository.save(product);
    }

    private Category getCategoryFromDB(String categoryName) {
        if(categoryName == null || categoryName.isBlank()) {
            return null;
        }

        Optional<Category> categoryOptional = categoryRepository.findByName(categoryName);
        if(categoryOptional.isPresent()){
            return categoryOptional.get();
        }

        Category newCategory = new Category();
        newCategory.setName(categoryName);
        try {
            return categoryRepository.save(newCategory);
        } catch (DataIntegrityViolationException e) {
            // Another request created this category after our lookup; the unique name constraint stopped a duplicate
            return categoryRepository.findByName(categoryName).orElseThrow();
        }
    }

    private void buildProduct(Product product,String name,String description ,double price,  String imageUrl, String category) {
        // This method should contain logic to build a product object
        product.setName(name);
        product.setDescription(description);
        product.setPrice(price);
        product.setImageUrl(imageUrl);

        Category categoryObj = getCategoryFromDB(category);
        product.setCategory(categoryObj);
    }
}
