package com.vanmool.productservice.services;

import com.vanmool.productservice.dtos.ProductRequestDto;
import com.vanmool.productservice.dtos.ProductResponseDto;
import com.vanmool.productservice.exceptions.ProductNotFoundException;
import com.vanmool.productservice.models.Category;
import com.vanmool.productservice.models.Product;
import com.vanmool.productservice.repositories.ProductRepository;
import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.github.fge.jsonpatch.JsonPatch;
import com.github.fge.jsonpatch.JsonPatchException;
import jakarta.validation.ConstraintViolation;
import jakarta.validation.ConstraintViolationException;
import jakarta.validation.Validator;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

// Each write runs in one transaction: the product is read, changed and saved in the same Hibernate session, so the
// change is all-or-nothing and the returned product's LAZY category is a loaded object, not a proxy that would fail
// once the session is closed. Reads need no transaction here: their queries fetch the category with @EntityGraph.
@Service
public class ProductDbService implements ProductService{
    private final CategoryService categoryService;
    private final ProductRepository productRepository;
    private final Validator validator;

    public ProductDbService(CategoryService categoryService, ProductRepository productRepository, Validator validator) {
        this.categoryService = categoryService;
        this.productRepository = productRepository;
        this.validator = validator;
    }

    @Override
    public Product getProductById(UUID id) throws ProductNotFoundException {
        Optional<Product> productOptional = productRepository.findByIdAndDeletedFalse(id);
        if(productOptional.isEmpty()) {
            throw new ProductNotFoundException("Product with id " + id + " not found");
        }

        return productOptional.get() ;
    }

    @Override
    public List<Product> getAllProducts() {
        return productRepository.findAllByDeletedFalse();
    }

    @Override
    public List<Product> getProductsByCategory(String categoryName) {
        return productRepository.findAllByCategory_NameAndDeletedFalse(categoryName);
    }

    @Override
    @Transactional
    public Product createProduct(ProductRequestDto productRequestDto) {
        Product product = new Product();
        buildProduct(product, productRequestDto);

        return productRepository.save(product);
    }

    @Override
    @Transactional
    public Product replaceProduct(UUID id, ProductRequestDto productRequestDto) throws ProductNotFoundException {
        // Ids are generated by the database, so PUT can only replace an existing product; creating is done by POST
        Product product = getProductById(id);
        buildProduct(product, productRequestDto);

        return productRepository.save(product);
    }

    @Override
    @Transactional
    public Product patchProduct(UUID id, JsonPatch patch) throws ProductNotFoundException, JsonPatchException, JsonProcessingException {
        Product existingProduct = getProductById(id);

        // Apply the patch to the same JSON that GET returns (the DTO), not to the entity
        ObjectMapper objectMapper = new ObjectMapper();
        JsonNode productNode = objectMapper.valueToTree(ProductResponseDto.from(existingProduct));
        JsonNode patchedNode = patch.apply(productNode);

        // A patch cannot change the id; everything else must pass the same rules as a POST or PUT body
        if(patchedNode instanceof ObjectNode objectNode) {
            objectNode.remove("id");
        }
        ProductRequestDto patchedProduct = objectMapper.treeToValue(patchedNode, ProductRequestDto.class);
        Set<ConstraintViolation<ProductRequestDto>> violations = validator.validate(patchedProduct);
        if(!violations.isEmpty()) {
            throw new ConstraintViolationException(violations);
        }

        buildProduct(existingProduct, patchedProduct);

        return productRepository.save(existingProduct);
    }

    @Override
    @Transactional
    public void deleteProduct(UUID id) throws ProductNotFoundException {
        // Soft delete: the row stays, so anything that refers to this product id keeps working
        Product product = getProductById(id);
        product.setDeleted(true);
        productRepository.save(product);
    }

    private void buildProduct(Product product, ProductRequestDto productRequestDto) {
        // Copies every field of the request onto the product, so a field left out of the request becomes null
        product.setName(productRequestDto.getName());
        product.setDescription(productRequestDto.getDescription());
        product.setPrice(productRequestDto.getPrice());
        product.setImageUrl(productRequestDto.getImageUrl());

        Category categoryObj = categoryService.findOrCreateCategory(productRequestDto.getCategory());
        product.setCategory(categoryObj);
    }
}
